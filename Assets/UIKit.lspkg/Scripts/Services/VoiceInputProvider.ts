import {Singleton} from "InteractionKit.lspkg/Decorators/Singleton"
import NativeLogger from "InteractionKit.lspkg/Utils/NativeLogger"
import {
  DEFAULT_SILENCE_UNTIL_TERMINATION_MS,
  getDeviceLanguage,
  normalizeLanguageTags,
  normalizeSilenceUntilTerminationMs,
  resolveVoiceInputLanguages
} from "../Utility/UIKitUtilities"

const log = new NativeLogger("VoiceInputProvider")

export type ListeningUpdate = [text: string, isFinal: boolean]

export type ActiveListeningCallbacks = {
  onListeningUpdate: (update: ListeningUpdate) => void
  onListeningError: (statusCode: AsrModule.AsrStatusCode) => void
  onListeningOwnershipLost: () => void
}

/**
 * Free-form hint bag passed through with the transcription options. Mirrors the shape of
 * `AsrTranscriptionOptions.extras`.
 */
type AsrTranscriptionExtras = {[key: string]: boolean | number | string}

/**
 * `AsrTranscriptionOptions` members that pre-377 Lens Studio declarations do not expose,
 * typed structurally (as CanvasController does for newer Canvas properties) so the kit
 * compiles against either declaration set.
 *
 * - `language`, `secondaryLanguages`, `version` and `extras` exist on the runtime, but a
 *   consumer compiling the published package against older declarations fails on any direct
 *   access (`Property 'extras' does not exist on type 'AsrTranscriptionOptions'`), so
 *   nothing here may touch them through the raw type.
 * - `secondaryLanguages` arrived in Lens API 377, so declarations generated by an older
 *   Lens Studio lack it entirely; see `applyLanguages` for the extras fallback.
 *
 * The shim is only needed while a supported declaration set predates Lens API 377.
 *
 * This is almost purely a typing change; the one behavioral difference is `version`, which
 * is documented `@defaultValue null`. The constructor guards on its value instead of
 * assuming one, so a runtime reporting no version object logs and keeps the default API
 * version rather than throwing. The other three need no runtime check — they default to
 * `"auto"`, `[]` and `{}`, never null.
 */
type CompatibleAsrTranscriptionOptions = AsrModule.AsrTranscriptionOptions & {
  language?: string
  secondaryLanguages?: string[]
  // Optional *and* nullable: absent from older declarations, and `@defaultValue null`.
  version?: {major: number} | null
  extras?: AsrTranscriptionExtras
}

/**
 * Extras key the speech backend reads secondary languages from, as a comma-separated
 * list. The engine folds the typed `secondaryLanguages` option into this same
 * key, so writing it directly is the equivalent path on
 * runtimes that predate the typed option.
 */
const SECONDARY_LANGUAGES_EXTRA_KEY = "secondary_languages"

/**
 * VoiceInputProvider wraps AsrModule, to convert voice into text.
 *
 * Every listening session tells ASR which languages to expect. The primary language
 * always comes from the device (`global.localizationSystem.getLanguage()`, read through
 * the guarded `getDeviceLanguage`) and falls back to `ASR_LANGUAGE_AUTO` only when the
 * device reports none or the localization system is unavailable; there is deliberately no
 * per-caller override. Callers configure the secondary languages speech may switch to —
 * e.g. the languages typical of a place the user is navigating to. A list passed to
 * `acquireListening()` wins over the provider-wide `defaultSecondaryLanguages`; see
 * `resolveVoiceInputLanguages`.
 *
 * Note: before secondary-language support, `language` was left at the module default
 * ("auto", detect the spoken language). Sending the device language instead follows the
 * ASR team's guidance to pass the user's locale as the primary language.
 */
@Singleton
export class VoiceInputProvider {
  public static getInstance: () => VoiceInputProvider

  // eslint-disable-next-line
  private readonly module = require("LensStudio:AsrModule") as AsrModule
  // Created through the public factory, then viewed through the compatible shape so every
  // member access below type-checks against both declaration sets (see the type's doc).
  private readonly options = AsrModule.AsrTranscriptionOptions.create() as CompatibleAsrTranscriptionOptions

  private listening = false
  private activeListeningOwner: object | null = null
  private activeListeningCallbacks: ActiveListeningCallbacks | null = null

  private _defaultSecondaryLanguages: string[] = []

  public constructor() {
    this.options.mode = AsrModule.AsrMode.HighAccuracy
    // Opt into ASR API v2. `version` is documented `@defaultValue null`, so this tests the
    // VALUE, not merely the property's presence: `"version" in this.options` would pass on
    // a null version and then throw on `.major`. (Contrast `applyLanguages`, where `in` is
    // the right test precisely because an absent *property* is what it detects.)
    const version = this.options.version
    if (version) {
      version.major = 2
    } else {
      // Without this the opt-in would be skipped silently on every session.
      log.d(`ASR options expose no version object; using the default API version`)
    }

    this.options.onTranscriptionUpdateEvent.add((evt) => {
      const update: ListeningUpdate = [evt.text, evt.isFinal]
      this.activeListeningCallbacks?.onListeningUpdate(update)
    })

    this.options.onTranscriptionErrorEvent.add((statusCode) => {
      log.d(`ASR module transcription error: ${statusCode}`)
      this.activeListeningCallbacks?.onListeningError(statusCode)
    })
  }

  public get isListening(): boolean {
    return this.listening
  }

  /**
   * Provider-wide secondary languages (BCP-47 tags) speech may switch to alongside the
   * device language, used when the session acquiring listening lists none of its own. A
   * lens that knows where the user is heading can set the destination's typical languages
   * here once instead of on every voice button. Returns a copy; assign a new array to
   * change it. Takes effect the next time listening starts.
   */
  public get defaultSecondaryLanguages(): string[] {
    return [...this._defaultSecondaryLanguages]
  }

  public set defaultSecondaryLanguages(value: readonly string[]) {
    this._defaultSecondaryLanguages = normalizeLanguageTags(value)
  }

  public acquireListening(
    owner: object,
    callbacks: ActiveListeningCallbacks,
    format: "default" | "search" | "url" = "default",
    silenceUntilTerminationMs: number = DEFAULT_SILENCE_UNTIL_TERMINATION_MS,
    secondaryLanguages: readonly string[] = []
  ): void {
    const previousOwner = this.activeListeningOwner
    const previousCallbacks = this.activeListeningCallbacks

    if (previousOwner !== owner && this.listening) {
      this.setListening(false)
    }

    this.activeListeningOwner = owner
    this.activeListeningCallbacks = callbacks

    if (previousOwner !== owner) {
      if (previousOwner && owner) {
        log.d(
          `ASR module ownership swapped from ${(previousOwner as any).sceneObject?.name ?? "unknown"} to ${(owner as any).sceneObject?.name ?? "unknown"}`
        )
      }
      previousCallbacks?.onListeningOwnershipLost()
    }

    const extras: AsrTranscriptionExtras = {lens: "SystemUI"}
    if (format !== "default") {
      extras.field_type = format
    }
    this.options.silenceUntilTerminationMs = normalizeSilenceUntilTerminationMs(silenceUntilTerminationMs)
    this.applyLanguages(secondaryLanguages, extras)
    this.options.extras = extras

    if (!this.listening) {
      this.setListening(true)
    }
  }

  public releaseListening(owner: object): void {
    if (this.activeListeningOwner !== owner) return

    this.activeListeningOwner = null
    this.activeListeningCallbacks = null

    if (this.listening) {
      this.setListening(false)
    }
  }

  /**
   * Resolves the session's languages (see `resolveVoiceInputLanguages`) and writes them
   * to the transcription options. Runs on every acquire so a changed device language or
   * updated defaults are picked up when listening next starts.
   *
   * Secondary languages use the typed `secondaryLanguages` option on Lens API 377+, and the
   * equivalent extras entry on older runtimes.
   */
  private applyLanguages(secondaryLanguages: readonly string[], extras: AsrTranscriptionExtras): void {
    const resolved = resolveVoiceInputLanguages(
      getDeviceLanguage(),
      secondaryLanguages,
      this._defaultSecondaryLanguages
    )
    this.options.language = resolved.language

    const hasTypedSecondaryLanguages = "secondaryLanguages" in this.options
    if (hasTypedSecondaryLanguages) {
      this.options.secondaryLanguages = resolved.secondaryLanguages
    } else if (resolved.secondaryLanguages.length > 0) {
      extras[SECONDARY_LANGUAGES_EXTRA_KEY] = resolved.secondaryLanguages.join(",")
    }
    log.d(
      `ASR languages: primary=${resolved.language}, secondary=[${resolved.secondaryLanguages.join(", ")}] via ${hasTypedSecondaryLanguages ? "secondaryLanguages option" : "extras fallback"}`
    )
  }

  private setListening(listening: boolean): void {
    if (this.listening === listening) return
    this.listening = listening

    if (listening) {
      log.d(`ASR module started transcribing`)
      this.module.startTranscribing(this.options)
    } else {
      log.d(`ASR module stopped transcribing`)
      this.module.stopTranscribing()
    }
  }
}
